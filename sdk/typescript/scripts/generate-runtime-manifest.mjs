#!/usr/bin/env node

import { mkdir, readFile, rename, rm, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const MAX_ARCHIVE_BYTES = 512 * 1024 * 1024;
const SHA256 = /^[0-9a-f]{64}$/u;
const VERSION = /^(?:0|[1-9][0-9]*)\.(?:0|[1-9][0-9]*)\.(?:0|[1-9][0-9]*)(?:-[0-9A-Za-z-]+(?:\.[0-9A-Za-z-]+)*)?$/u;
const SOURCE_KEYS = [
  "pliego_repository",
  "pliego_revision",
  "pliego_servo_merge_base",
  "servo_repository",
  "servo_revision",
  "stasis_repository",
  "stasis_revision",
];
export const ARCHIVE_FILES = [
  "INSTALL.txt",
  "LICENSE",
  "LICENSE_WHATWG_SPECS",
  "NATIVE-LIBRARIES.txt",
  "README.md",
  "SOURCE.txt",
  "STASIS_UPSTREAM.toml",
  "THIRD_PARTY_LICENSES.html",
  "VERSION.txt",
  "stasis",
];
export const PLATFORMS = {
  "darwin-arm64": ["darwin", "arm64", "macos-aarch64"],
  "linux-x64": ["linux", "x64", "linux-x86_64"],
};
export const GENERATED_MODULE_PREFIX = `/* Generated by scripts/generate-runtime-manifest.mjs. Do not edit. */\nimport type { RuntimeDistributionManifest } from "./runtime-manifest.js";\n\nexport const RUNTIME_DISTRIBUTION_MANIFEST = `;
export const GENERATED_MODULE_SUFFIX = " as const satisfies RuntimeDistributionManifest;\n";

function fail(message) {
  throw new Error(`runtime manifest: ${message}`);
}

function exactKeys(value, expected, label) {
  if (value === null || typeof value !== "object" || Array.isArray(value)) fail(`${label} must be an object`);
  const actual = Object.keys(value).sort();
  const wanted = [...expected].sort();
  if (JSON.stringify(actual) !== JSON.stringify(wanted)) fail(`${label} has unexpected or missing fields`);
}

function string(value, label) {
  if (typeof value !== "string" || value.length === 0) fail(`${label} must be a non-empty string`);
  return value;
}

export function validateRuntimeManifest(manifest) {
  exactKeys(manifest, ["schema", "packageName", "sdkVersion", "releaseTag", "implementation", "artifacts"], "root");
  if (manifest.schema !== 1 || manifest.packageName !== "@oxhq/stasis") fail("unsupported schema or package");
  if (!VERSION.test(manifest.sdkVersion) || manifest.releaseTag !== `v${manifest.sdkVersion}`) fail("version/tag mismatch");
  exactKeys(manifest.implementation, ["name", "source"], "implementation");
  if (manifest.implementation.name !== "stasis-shell") fail("unexpected implementation name");
  exactKeys(manifest.implementation.source, SOURCE_KEYS, "implementation.source");
  for (const key of SOURCE_KEYS) {
    const value = string(manifest.implementation.source[key], `implementation.source.${key}`);
    if (key.endsWith("revision") || key === "pliego_servo_merge_base") {
      if (!/^[0-9a-f]{40}$/u.test(value)) fail(`${key} must be a full lowercase commit SHA`);
    } else {
      const url = new URL(value);
      if (url.protocol !== "https:" || url.username || url.password || url.hash) fail(`${key} must be a clean HTTPS URL`);
    }
  }
  exactKeys(manifest.artifacts, Object.keys(PLATFORMS), "artifacts");
  for (const platformKey of Object.keys(PLATFORMS).sort()) {
    const artifact = manifest.artifacts[platformKey];
    exactKeys(artifact, [
      "nodePlatform", "nodeArch", "releasePlatform", "archiveUrl", "archiveSizeBytes",
      "archiveSha256", "archiveRoot", "archiveFiles", "executablePath", "executableSha256",
    ], `artifacts.${platformKey}`);
    const [nodePlatform, nodeArch, releasePlatform] = PLATFORMS[platformKey];
    if (artifact.nodePlatform !== nodePlatform || artifact.nodeArch !== nodeArch || artifact.releasePlatform !== releasePlatform) {
      fail(`${platformKey} platform identity mismatch`);
    }
    const root = `stasis-${manifest.sdkVersion}-${releasePlatform}`;
    if (artifact.archiveRoot !== root || artifact.executablePath !== "stasis") fail(`${platformKey} archive layout mismatch`);
    if (!Number.isSafeInteger(artifact.archiveSizeBytes) || artifact.archiveSizeBytes < 1 || artifact.archiveSizeBytes > MAX_ARCHIVE_BYTES) {
      fail(`${platformKey} archive size is outside the release bound`);
    }
    if (!SHA256.test(artifact.archiveSha256) || !SHA256.test(artifact.executableSha256)) fail(`${platformKey} has an invalid SHA-256`);
    if (JSON.stringify(artifact.archiveFiles) !== JSON.stringify(ARCHIVE_FILES)) fail(`${platformKey} must bind the exact stable archive inventory`);
    const url = new URL(string(artifact.archiveUrl, `${platformKey}.archiveUrl`));
    const expectedPath = `/oxhq/stasis/releases/download/${manifest.releaseTag}/${root}.tar.gz`;
    if (url.protocol !== "https:" || url.hostname !== "github.com" || url.port || url.username || url.password || url.hash || url.search || url.pathname !== expectedPath) {
      fail(`${platformKey} archive URL does not match the exact GitHub release asset`);
    }
  }
}

export function canonicalizeRuntimeManifest(manifest) {
  const source = Object.fromEntries(SOURCE_KEYS.map((key) => [key, manifest.implementation.source[key]]));
  const artifacts = {};
  for (const key of Object.keys(PLATFORMS).sort()) {
    const artifact = manifest.artifacts[key];
    artifacts[key] = {
      nodePlatform: artifact.nodePlatform,
      nodeArch: artifact.nodeArch,
      releasePlatform: artifact.releasePlatform,
      archiveUrl: artifact.archiveUrl,
      archiveSizeBytes: artifact.archiveSizeBytes,
      archiveSha256: artifact.archiveSha256,
      archiveRoot: artifact.archiveRoot,
      archiveFiles: [...artifact.archiveFiles],
      executablePath: artifact.executablePath,
      executableSha256: artifact.executableSha256,
    };
  }
  return {
    schema: 1,
    packageName: "@oxhq/stasis",
    sdkVersion: manifest.sdkVersion,
    releaseTag: manifest.releaseTag,
    implementation: { name: "stasis-shell", source },
    artifacts,
  };
}

export function assertNoDuplicateJsonKeys(document) {
  let offset = 0;
  const whitespace = () => { while (/\s/u.test(document[offset] ?? "")) offset += 1; };
  const parseString = () => {
    const start = offset++;
    while (offset < document.length) {
      if (document[offset] === "\\") { offset += 2; continue; }
      if (document[offset++] === "\"") return JSON.parse(document.slice(start, offset));
    }
    fail("unterminated JSON string");
  };
  const parseValue = () => {
    whitespace();
    if (document[offset] === "{") return parseObject();
    if (document[offset] === "[") {
      offset += 1; whitespace();
      if (document[offset] === "]") { offset += 1; return; }
      while (true) {
        parseValue(); whitespace();
        if (document[offset] === "]") { offset += 1; return; }
        if (document[offset++] !== ",") fail("invalid JSON array");
      }
    }
    if (document[offset] === "\"") { parseString(); return; }
    const match = /^(?:true|false|null|-?(?:0|[1-9][0-9]*)(?:\.[0-9]+)?(?:[eE][+-]?[0-9]+)?)/u.exec(document.slice(offset));
    if (match === null) fail("invalid JSON value");
    offset += match[0].length;
  };
  const parseObject = () => {
    offset += 1; whitespace();
    const keys = new Set();
    if (document[offset] === "}") { offset += 1; return; }
    while (true) {
      if (document[offset] !== "\"") fail("JSON object key must be a string");
      const key = parseString();
      if (keys.has(key)) fail(`duplicate JSON object key ${JSON.stringify(key)}`);
      keys.add(key); whitespace();
      if (document[offset++] !== ":") fail("invalid JSON object");
      parseValue(); whitespace();
      if (document[offset] === "}") { offset += 1; return; }
      if (document[offset++] !== ",") fail("invalid JSON object");
      whitespace();
    }
  };
  parseValue(); whitespace();
  if (offset !== document.length) fail("trailing JSON data");
}

function argumentsFrom(argv) {
  if (argv.length !== 4 || argv[0] !== "--input" || argv[2] !== "--output") {
    fail("usage: generate-runtime-manifest.mjs --input <strict-json> --output <generated-ts>");
  }
  return { input: resolve(argv[1]), output: resolve(argv[3]) };
}

export function parseStrictJson(document) {
  assertNoDuplicateJsonKeys(document);
  return JSON.parse(document);
}

export function renderRuntimeManifestModule(manifest) {
  validateRuntimeManifest(manifest);
  return `${GENERATED_MODULE_PREFIX}${JSON.stringify(canonicalizeRuntimeManifest(manifest), null, 2)}${GENERATED_MODULE_SUFFIX}`;
}

async function main(argv) {
  const paths = argumentsFrom(argv);
  const document = await readFile(paths.input, "utf8");
  const parsed = parseStrictJson(document);
  const body = renderRuntimeManifestModule(parsed);
  await mkdir(dirname(paths.output), { recursive: true });
  const temporary = `${paths.output}.tmp-${process.pid}`;
  try {
    await writeFile(temporary, body, { encoding: "utf8", flag: "wx", mode: 0o600 });
    await rename(temporary, paths.output);
  } finally {
    await rm(temporary, { force: true });
  }
}

if (process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await main(process.argv.slice(2));
}
